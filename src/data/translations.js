const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [currentLang, setCurrentLang] = useState(() => {
    try {
      return localStorage.getItem('kisanqueue_lang') || 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = (lang) => {
    setCurrentLang(lang);
    try {
      localStorage.setItem('kisanqueue_lang', lang);
    } catch (e) {
      console.warn('localStorage error', e);
    }
  };

  /**
   * Translate key with optional parameter interpolation
   * Example: t('dashboard.welcome', { name: 'Ramesh' }) -> "Welcome, Ramesh 👋"
   */
  const t = (key, paramsOrFallback = {}) => {
    let params = {};
    let fallback = '';

    if (typeof paramsOrFallback === 'string') {
      fallback = paramsOrFallback;
    } else if (typeof paramsOrFallback === 'object' && paramsOrFallback !== null) {
      params = paramsOrFallback;
      fallback = params.fallback || '';
    }

    const langDict = translations[currentLang] || translations.en;
    let text = langDict[key] || translations.en[key] || fallback || key;

    // Parameter interpolation: replace {{param}} or {param}
    if (params && typeof text === 'string') {
      Object.keys(params).forEach((paramKey) => {
        const value = params[paramKey];
        if (value !== undefined && value !== null) {
          const doubleRegex = new RegExp(`{{\\s*${paramKey}\\s*}}`, 'g');
          const singleRegex = new RegExp(`{\\s*${paramKey}\\s*}`, 'g');
          text = text.replace(doubleRegex, String(value)).replace(singleRegex, String(value));
        }
      });
    }

    return text;
  };

  return React.createElement(
    LanguageContext.Provider,
    { value: { currentLang, setLanguage, t } },
    children
  );
};

export const useTranslation = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      currentLang: 'en',
      setLanguage: () => { },
      t: (key, paramsOrFallback = {}) => {
        let params = typeof paramsOrFallback === 'object' ? paramsOrFallback : {};
        let text = translations.en[key] || (typeof paramsOrFallback === 'string' ? paramsOrFallback : key);
        if (params && typeof text === 'string') {
          Object.keys(params).forEach((paramKey) => {
            const doubleRegex = new RegExp(`{{\\s*${paramKey}\\s*}}`, 'g');
            text = text.replace(doubleRegex, String(params[paramKey]));
          });
        }
        return text;
      }
    };
  }
  return context;
};

